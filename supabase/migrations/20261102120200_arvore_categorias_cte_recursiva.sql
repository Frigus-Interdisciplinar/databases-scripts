-- Hierarquia de categorias de produto (requisito 6: CTE recursiva).
-- product_categories tem parent_id apontando para a própria tabela; as folhas se ligam a products.category via enum_value.
-- Segue a regra de segurança das tabelas novas: RLS ligado e sem grants para anon/authenticated.

CREATE TABLE IF NOT EXISTS public.product_categories (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(80) NOT NULL UNIQUE,
    parent_id  integer REFERENCES public.product_categories (id),
    enum_value category_enum UNIQUE
);

